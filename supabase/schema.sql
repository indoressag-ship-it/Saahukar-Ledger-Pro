create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  plan text not null default 'free' check (plan in ('free', 'pro')),
  status text not null default 'active' check (status in ('active', 'expired', 'cancelled', 'payment_failed', 'pending')),
  billing_cycle text check (billing_cycle in ('monthly', 'yearly')),
  start_date timestamptz not null default now(),
  expiry_date timestamptz,
  payment_provider text,
  payment_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists subscriptions_user_id_idx on public.subscriptions(user_id);
create index if not exists subscriptions_plan_status_expiry_idx on public.subscriptions(plan, status, expiry_date);

alter table public.subscriptions enable row level security;

drop policy if exists "Users can view their own subscription" on public.subscriptions;
create policy "Users can view their own subscription"
  on public.subscriptions for select
  to authenticated
  using (auth.uid() = user_id);

revoke all on public.subscriptions from anon, authenticated;
grant select on public.subscriptions to authenticated;
grant all on public.subscriptions to service_role;

create or replace function public.create_free_subscription_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.subscriptions (user_id, plan, status, start_date)
  values (new.id, 'free', 'active', now())
  on conflict (user_id) do nothing;
  return new;
end;
$$;

revoke all on function public.create_free_subscription_for_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_subscription on auth.users;
create trigger on_auth_user_created_subscription
  after insert on auth.users
  for each row execute function public.create_free_subscription_for_new_user();

insert into public.subscriptions (user_id, plan, status, start_date)
select users.id, 'free', 'active', now()
from auth.users as users
on conflict (user_id) do nothing;

create or replace function public.update_subscription_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists subscriptions_updated_at on public.subscriptions;
create trigger subscriptions_updated_at
  before update on public.subscriptions
  for each row execute function public.update_subscription_updated_at();

revoke all on function public.update_subscription_updated_at() from public, anon, authenticated;

